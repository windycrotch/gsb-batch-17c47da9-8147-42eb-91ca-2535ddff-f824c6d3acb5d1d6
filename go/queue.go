func (s *ProcessingQueue) FetchSrcAssets(trackNumber int, clipNumber int, clip Clip, useCache bool, typeAsset interface{}) bool {
	var hasError bool

	var assetHandled bool
	var assetSrc string
	switch GetAssetType(typeAsset) { // nolint:exhaustive
	case ImageAssetType:
		asset := clip.Asset.(*ImageAsset)
		assetSrc = asset.Src
		assetHandled = true
	case VideoAssetType:
		asset := clip.Asset.(*VideoAsset)
		assetSrc = asset.Src
		assetHandled = true
	case AudioAssetType:
		asset := clip.Asset.(*AudioAsset)
		assetSrc = asset.Src
	case LumaAssetType:
		asset := clip.Asset.(*LumaAsset)
		assetSrc = asset.Src
	}

	s.ensureResources()
	s.resourcesMu.Lock()
	existing := s.LocalResources[assetSrc]
	s.resourcesMu.Unlock()

	if existing == nil || existing.Cleaned {
		var fileName string
		var remote bool
		parsedURL, _ := url.Parse(assetSrc)

		if parsedURL != nil && parsedURL.Scheme == "file" {
			fileName = assetSrc[7:]
		} else {
			var err error
			fileName, err = s.DownloadFile(assetSrc)
			if err != nil {
				fmt.Println("Error while downloading asset", err)
				hasError = true
			}
			remote = true
		}

		if !hasError {
			fmt.Println("Asset downloaded: "+assetSrc, fileName)
			localResource := &LocalResource{
				Downloaded:       time.Now(),
				OriginalURL:      assetSrc,
				LocalURL:         fileName,
				KeepCache:        useCache,
				IsRemoteResource: remote,
			}
			s.resourcesMu.Lock()
			// Another goroutine may have inserted a valid resource first.
			if current := s.LocalResources[assetSrc]; current != nil && !current.Cleaned {
				localResource = current
			} else {
				s.LocalResources[assetSrc] = localResource
			}
			s.resourcesMu.Unlock()
		}
	}

	if !hasError {
		s.resourcesMu.Lock()
		resource := s.LocalResources[assetSrc]
		if resource != nil {
			resource.Used = append(
				resource.Used,
				&LocalResourceTrackInfo{
					Track:   trackNumber,
					Clip:    clipNumber,
					Handled: assetHandled,
				})
		}
		s.resourcesMu.Unlock()
	}

	return hasError
}

func (s *ProcessingQueue) ensureResources() {
	s.resourcesMu.Lock()
	if s.LocalResources == nil {
		s.LocalResources = make(map[string]*LocalResource)
	}
	s.resourcesMu.Unlock()
}

