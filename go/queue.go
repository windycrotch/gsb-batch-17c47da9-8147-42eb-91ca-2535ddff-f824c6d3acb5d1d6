// queueLoop is the single dispatcher: renders are processed one at a time, but
// every render owns an independent state machine. A failure/panic of one render
// can never prevent later queued renders from running.
func (s *ProcessingQueue) queueLoop(editAPI EditAPIServicer) {
	defer s.loopWg.Done()

	// Preserve the historical delay before the first pump. A manual
	// ProcessQueue kick or Stop interrupts the wait.
	startTimer := time.NewTimer(QueueStartDelay)
	defer startTimer.Stop()
	pollTicker := time.NewTicker(QueuePollInterval)
	defer pollTicker.Stop()

	first := true
	for {
		if first {
			select {
			case <-startTimer.C:
			case <-s.wake:
			case <-s.stop:
				return
			}
			first = false
		} else {
			select {
			case <-s.wake:
			case <-pollTicker.C:
			case <-s.stop:
				return
			}
		}
		s.drainQueue(editAPI)
	}
}

// drainQueue claims and runs every currently queued render in submission order.
