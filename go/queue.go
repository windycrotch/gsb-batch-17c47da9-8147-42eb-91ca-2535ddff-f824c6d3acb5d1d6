func (s *ProcessingQueue) prepareGIFSkiFor(render *RenderQueue) ([]string, error) {
	parameters := make([]string, 0)
	parameters = append(parameters, "-o")
	if render == nil || render.FFMPEGCommand == nil {
		return make([]string, 0), errors.New("impossible to prepare GIF: missing render command")
	}
	parameters = append(parameters, render.FFMPEGCommand.GetOutputName())
	parameters = append(parameters, "--repeat")
	repeat := render.FFMPEGCommand.GetOutputRepeat()
	if repeat {
		parameters = append(parameters, "0")
	} else {
		parameters = append(parameters, "-1")
	}

	err := filepath.Walk(os.TempDir(), func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return nil // nolint: nilerr
		}
		if info.IsDir() && path != os.TempDir() {
			return filepath.SkipDir
		}
		if strings.Contains(info.Name(), render.ID) {
			parameters = append(parameters, path)
		}
		return nil
	})

	if len(parameters) == 2 {
		return make([]string, 0), errors.New("impossible to detect PNGs to create GIF")
	}

	return parameters, err
}

