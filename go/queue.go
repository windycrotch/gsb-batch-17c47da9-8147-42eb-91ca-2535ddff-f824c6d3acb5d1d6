// callbackRetryTiming is the historical webhook retry rhythm, in seconds.
// Index 0 corresponds to the initial delivery and is not used as a delay.
var callbackRetryTiming = []int{0, 8, 27, 64, 125, 216, 343, 512, 729, 900}

// CallbackRetryDelay resolves the wait before retry attempt retry (retry >= 1).
// It is a variable so acceptance tests can compress the long backoff without
// changing the production retry rhythm.
var CallbackRetryDelay = func(retry int) time.Duration {
	if retry >= 0 && retry < len(callbackRetryTiming) {
		return time.Duration(callbackRetryTiming[retry]) * time.Second
	}
	return 0
}

// QueuePollInterval is how often the background loop checks for newly queued
// renders. It is a variable so tests can run with a fast cadence.
var QueuePollInterval = time.Second

// QueueStartDelay preserves the historical delay between starting the queue and
// the first processing tick. Tests may lower it.
var QueueStartDelay = time.Second

