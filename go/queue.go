// fetchAssetsFor performs all asset downloads for one render. It returns true
// when at least one asset could not be fetched and marks the render Failed.
func (s *ProcessingQueue) fetchAssetsFor(queue *RenderQueue) bool {
	queue.Transition(Fetching, Fetching)

	var hasError bool

	useCache := queue.Data.Timeline.Cache

	for tIndex, track := range queue.Data.Timeline.Tracks {
		for cIndex, clip := range track.Clips {
			// fmt.Println(tIndex, cIndex, clip.Asset.Type)

			var typeAsset = GetAssetType(clip.Asset)
			var clipError bool
			switch typeAsset { // nolint:exhaustive
			case VideoAssetType:
				clipError = s.FetchSrcAssets(tIndex, cIndex, clip, useCache, &VideoAsset{})
			case ImageAssetType:
				clipError = s.FetchSrcAssets(tIndex, cIndex, clip, useCache, &ImageAsset{})
			case TitleAssetType: // Nothing to do
			case HTMLAssetType: // Nothing to do
			case AudioAssetType:
				clipError = s.FetchSrcAssets(tIndex, cIndex, clip, useCache, &AudioAsset{})
			case LumaAssetType:
				clipError = s.FetchSrcAssets(tIndex, cIndex, clip, useCache, &LumaAsset{})
			default:
				fmt.Println("Unhandled asset type", typeAsset.String())
			}
			hasError = hasError || clipError
		}
	}

	// Dev Only
	// fmt.Println(queue.LocalResources)

	if hasError {
		queue.Fail("Error while fetching assets")
		return true
	}

	queue.Transition(Fetching, Fetched)
	return false
}

func (s *ProcessingQueue) DownloadFile(fileURL string) (string, error) {
	extension := filepath.Ext(fileURL)
	if parsedURL, err := url.Parse(fileURL); err == nil && parsedURL != nil && parsedURL.Path != "" {
		extension = filepath.Ext(parsedURL.Path)
	}

	file, err := os.CreateTemp("", "asset*"+extension)
	if err != nil {
		fmt.Println("Error temp file", err)
		return "", err
	}
	fileName := file.Name()
	defer file.Close()
	fmt.Println("----" + file.Name())

	// Get the data
	resp, err := http.Get(fileURL) // nolint:gosec,G107
	if err != nil {
		_ = os.Remove(fileName)
		return "", err
	}
	defer resp.Body.Close()

	if resp.StatusCode < 200 || resp.StatusCode > 299 {
		_, _ = io.Copy(io.Discard, resp.Body)
		_ = os.Remove(fileName)
		return "", fmt.Errorf("download asset %s returned unexpected status code %d", fileURL, resp.StatusCode)
	}

	fmt.Println(resp.Body)

	// Write the body to file
	_, err = io.Copy(file, resp.Body)
	if err != nil {
		_ = os.Remove(fileName)
		return "", err
	}
	return file.Name(), nil
}

func (s *ProcessingQueue) ExecuteCallback(queue RenderQueue, errorLabel string, retry int) {
	// See https://shotstack.io/docs/guide/architecting-an-application/webhooks/
	if queue.Data.Callback != "" {
		fmt.Println("ExecuteCallback for", queue.ID, "#", retry)

		response := &CallbackResponse{
			Type:   "edit",
			Action: "render",
			ID:     queue.ID,
			Owner:  "me",
			Status: "done",
		}
		if errorLabel != "" {
			response.Status = "failed"
			response.Error = &errorLabel
		} else {
			if s.config != nil {
				response.URL = s.config.GetDownloadBaseURL() + "/renders/" + queue.ID
			} else {
				response.URL = "/renders/" + queue.ID
			}
			response.Completed = queue.Updated.Format("2006-01-02T15:04:05.123Z")
		}
		jsonData, errConvert := json.Marshal(response)

		if errConvert != nil {
			// Marshalling this fixed response cannot realistically fail; never
			// terminate the whole server over a callback.
			fmt.Println("Error while encoding callback", errConvert)
			return
		}

		client := http.Client{Timeout: 10 * time.Second}

		resp, err := client.Post(queue.Data.Callback, "application/json", bytes.NewBuffer(jsonData))
		requestFailed := false
		if err != nil {
			// A connection/timeout error is a delivery failure: retry below
			// instead of calling log.Fatal and killing the process.
			fmt.Println("Error while sending callback", queue.ID, err)
			requestFailed = true
		} else {
			defer resp.Body.Close()
			if resp.StatusCode < 200 || resp.StatusCode > 399 {
				requestFailed = true
			}
		}

		// Retry with the historical rhythm, bounded by the schedule length so
		// the last scheduled retry never indexes past the slice.
		if requestFailed && retry+1 < len(callbackRetryTiming) {
			newRetry := retry + 1
			delay := CallbackRetryDelay(newRetry)
			fmt.Println("Retry #" + cast.ToString(newRetry) + " in " + delay.String())

			time.AfterFunc(delay, func() {
				s.ExecuteCallback(queue, errorLabel, newRetry)
			})
		}
	}
}
