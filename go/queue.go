// claimNextRender atomically reserves the oldest Queued render.
func (s *ProcessingQueue) claimNextRender(editAPI EditAPIServicer) *RenderQueue {
	pending := editAPI.GetQueuePending()
	for _, render := range pending {
		if render == nil {
			continue
		}
		render.lockState()
		if render.Status != Queued {
			render.unlockState()
			continue
		}

		now := time.Now()
		render.Status = Fetching
		render.InternalStatus = Fetching
		render.Updated = now
		if render.FFMPEGCommand == nil {
			render.FFMPEGCommand = NewFFMPEGCommand()
		}

		// Set Resolution (Mandatory for Filler)
		if render.Data.Output.Resolution != "" {
			_ = render.FFMPEGCommand.SetOutputResolution(render.Data.Output.Resolution)
		} else if render.Data.Output.Size != nil {
			_ = render.FFMPEGCommand.SetOutputSize(render.Data.Output.Size.Width, render.Data.Output.Size.Height)
		}
		render.unlockState()

		s.setCurrentRender(render)
		fmt.Println(render.ID)
		return render
	}
	return nil
}

// processRender runs the full fetch -> generate -> ffmpeg -> done/failed ->
// cleanup -> callback lifecycle for exactly one render.
func (s *ProcessingQueue) processRender(render *RenderQueue) {
	callbackLabel := ""
	sendCallback := false

	defer func() {
		if recovered := recover(); recovered != nil {
			fmt.Printf("Recovered while processing render %s: %v\n", render.ID, recovered)
			if render.Fail("Internal error while processing render") {
				callbackLabel = "Internal error while processing render"
				sendCallback = true
			}
		}

		if sendCallback {
			// Clean temporary source assets before notifying; retained cache
			// assets are left on disk by cleanupRenderAssets.
			s.cleanupRenderAssets()
			label := callbackLabel
			go s.ExecuteCallback(render.Copy(), label, 0)
		}

		s.clearCurrentRender(render)
		s.kick()
	}()

	fmt.Println("Processing render", render.ID)

	if s.fetchAssetsFor(render) {
		s.cleanupRenderAssets()
		render.Fail("Error while fetching assets")
		callbackLabel = "Error while fetching assets"
		sendCallback = true
		return
	}

	params := s.GenerateParameters(render)
	render.MarkUpdated()

	if err := s.runFFMpegFor(render, params); err != nil {
		s.cleanupRenderAssets()
		render.Fail("Error with FFMPEG")
		callbackLabel = "Error with FFMPEG"
		sendCallback = true
		return
	}

	if render.Data.Output.Format == "gif" && render.Data.Output.Quality == "high" {
		parameters, err := s.prepareGIFSkiFor(render)
		if err != nil {
			fmt.Println(err)
			s.cleanupRenderAssets()
			render.Fail("Error with GIFski")
			callbackLabel = "Error with GIFski"
			sendCallback = true
			return
		}
		if err := s.runGIFSkiFor(render, parameters); err != nil {
			s.cleanupRenderAssets()
			render.Fail("Error with GIFski")
			callbackLabel = "Error with GIFski"
			sendCallback = true
			return
		}
	}

	// Clean temporary source assets before publishing the terminal state so
	// that observers seeing done/failed also see finished cleanup. Assets
	// flagged KeepCache are retained on disk.
	s.cleanupRenderAssets()

	// Pass through the Saving state and immediately complete, matching the
	// historical state machine.
	render.Transition(Saving, Saving)
	if cmd := render.GetFFMPEGCommand(); cmd != nil {
		render.SetFileName(cmd.GetOutputName())
	}
	render.Transition(Done, Done)

	sendCallback = true
}

func (s *ProcessingQueue) CleanCache() {
	s.resourcesMu.Lock()
	for _, resource := range s.LocalResources {
		if resource == nil || resource.KeepCache {
			continue
		}
		// Remove local asset only if remote resource
		if resource.IsRemoteResource && !resource.Cleaned {
			_ = os.Remove(resource.LocalURL)
			resource.Cleaned = true
		}
		s.LocalResources[resource.OriginalURL] = nil
	}
	s.resourcesMu.Unlock()

	go time.AfterFunc(1*time.Hour, func() {
		s.CleanCache()
	})
}

// cleanupRenderAssets removes the temporary downloaded source files for the
// render that just reached a terminal state. Resources flagged KeepCache are
// left on disk. The metadata entry is retained (marked Cleaned) so status and
// diagnostics stay inspectable; later renders download the URL again.
func (s *ProcessingQueue) cleanupRenderAssets() {
	s.resourcesMu.Lock()
	defer s.resourcesMu.Unlock()

	for _, resource := range s.LocalResources {
		if resource == nil || resource.KeepCache || !resource.IsRemoteResource || resource.Cleaned {
			continue
		}
		if err := os.Remove(resource.LocalURL); err != nil && !os.IsNotExist(err) {
			fmt.Println("Error while cleaning asset", resource.LocalURL, err)
			continue
		}
		resource.Cleaned = true
	}
}

